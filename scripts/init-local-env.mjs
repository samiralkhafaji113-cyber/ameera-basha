/**
 * Writes .env.local for LOCAL development from `supabase status` (values are never printed).
 * Also generates a random password for a local-only test admin (stored ONLY in .env.local, which is git-ignored).
 * Safe to re-run: existing values in .env.local are preserved unless --force is passed.
 *
 *   node scripts/init-local-env.mjs [--force]
 */
import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const target = path.join(ROOT, ".env.local");
const force = process.argv.includes("--force");

const raw = execFileSync("npx", ["--yes", "supabase@2.117.0", "status", "-o", "env"], { cwd: ROOT, encoding: "utf8", shell: true, stdio: ["ignore", "pipe", "ignore"] });
const status = Object.fromEntries(
  raw
    .split(/\r?\n/)
    .map((l) => l.match(/^([A-Z_]+)="?(.*?)"?$/))
    .filter(Boolean)
    .map((m) => [m[1], m[2]]),
);
for (const k of ["API_URL", "ANON_KEY", "SERVICE_ROLE_KEY"]) if (!status[k]) throw new Error(`supabase status did not return ${k} – is the local stack running?`);

const existing = fs.existsSync(target) && !force ? Object.fromEntries(fs.readFileSync(target, "utf8").split(/\r?\n/).filter((l) => l && !l.startsWith("#")).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)])) : {};

const pw = () => "Ab-" + randomBytes(9).toString("base64url").replace(/[-_]/g, "x") + "9z";
const values = {
  NEXT_PUBLIC_SITE_URL: existing.NEXT_PUBLIC_SITE_URL ?? "http://localhost:3100",
  NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
  NEXT_PUBLIC_SUPABASE_ANON_KEY: status.ANON_KEY,
  SUPABASE_SERVICE_ROLE_KEY: status.SERVICE_ROLE_KEY,
  E2E_ADMIN_EMAIL: existing.E2E_ADMIN_EMAIL ?? "admin@ameera.test",
  E2E_ADMIN_PASSWORD: existing.E2E_ADMIN_PASSWORD ?? pw(),
  E2E_EDITOR_EMAIL: existing.E2E_EDITOR_EMAIL ?? "editor@ameera.test",
  E2E_EDITOR_PASSWORD: existing.E2E_EDITOR_PASSWORD ?? pw(),
};
const header = "# LOCAL development only – generated by scripts/init-local-env.mjs. Never commit. SUPABASE_SERVICE_ROLE_KEY is for operator scripts, never for app code.\n";
fs.writeFileSync(target, header + Object.entries(values).map(([k, v]) => `${k}=${v}`).join("\n") + "\n");
console.log("Wrote .env.local with keys:", Object.keys(values).join(", "), "(values hidden)");
